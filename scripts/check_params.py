#!/usr/bin/env python3
"""Checks the documented model parameters. Fails on any problem.

Checks model-spec/parameters.yaml itself (all fields given, valid category,
value within range, unique names and labels), and that the model entries of
the given model config files (by default, those shipped with both
implementations) match it: the same resources and systems, in the same
order, with the same parameter values. Reporters (`CSV`) and module-qualified
types (e.g. Julia's `Main.TimeSeries` plots) are not model entries and are
ignored, as is everything else but `resources` and `systems`.

Whether the documented parameters match what the models actually accept is
not checked here, but by running both models with the config generated by
scripts/params_to_config.py.

Usage: python scripts/check_params.py [-p parameters.yaml] [config.yaml ...]
       (defaults: ../model-spec/parameters.yaml, ../pwn/config.yaml ../PWNModel.jl/config.yaml)

Requires PyYAML.
"""

import argparse
import difflib
import sys
from collections import Counter
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent

PARAM_FIELDS = ["name", "symbol", "description", "value", "unit", "range", "category", "source"]
CATEGORIES = {"technical", "ecological", "management", "scenario"}

# System types in model configs that are not model entries.
IGNORED_TYPES = {"CSV"}


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("-p", "--params", default=ROOT.parent / "model-spec" / "parameters.yaml",
                        help="documented parameters (default: %(default)s)")
    parser.add_argument("configs", nargs="*",
                        default=[ROOT.parent / "pwn" / "config.yaml", ROOT.parent / "PWNModel.jl" / "config.yaml"],
                        help="model config files to compare with the documented parameters")
    args = parser.parse_args()

    params = load(args.params)

    ok = report(args.params, check_params(params))
    for config in args.configs:
        ok = report(config, check_config(params, load(config))) and ok

    sys.exit(0 if ok else 1)


def load(path):
    with open(path, encoding="utf-8") as f:
        return yaml.safe_load(f) or {}


def report(path, errors):
    """Prints the errors found in the file at path. Returns whether there are none."""
    if not errors:
        print(f"OK   {path}")
        return True
    print(f"FAIL {path}")
    for e in errors:
        print(f"     {e}")
    return False


def check_params(doc):
    """Returns a list of problems in a parsed parameters document."""
    errors = []
    for section in ("resources", "systems"):
        entries = doc.get(section) or []
        type_counts = Counter(e.get("type") for e in entries)
        labels = Counter()
        for i, entry in enumerate(entries):
            typ = entry.get("type")
            where = f"{section}[{i}] ({typ})"
            if not typ:
                errors.append(f"{where}: missing type")
            if not entry.get("description"):
                errors.append(f"{where}: missing description")
            if type_counts[typ] > 1:
                if not entry.get("label"):
                    errors.append(f"{where}: type appears more than once, but entry has no label")
                else:
                    labels[(typ, entry["label"])] += 1
            if not isinstance(entry.get("parameters"), list):
                errors.append(f"{where}: parameters must be a list (empty if there are none)")
                continue

            names = Counter(p.get("name") for p in entry["parameters"])
            errors += [f"{where}: duplicate parameter {n!r}" for n, c in names.items() if c > 1]
            for param in entry["parameters"]:
                errors += [f"{where}.{param.get('name')}: {e}" for e in check_param(param)]
        errors += [f"{section}: duplicate label {label!r} for {typ}" for (typ, label), c in labels.items() if c > 1]
    return errors


def check_param(param):
    """Returns a list of problems with a documented parameter."""
    errors = [f"missing field {f!r}" for f in PARAM_FIELDS if f not in param]
    errors += [f"unknown field {f!r}" for f in param if f not in PARAM_FIELDS]

    category = param.get("category")
    if "category" in param and category not in CATEGORIES:
        errors.append(f"category {category!r} is not one of {', '.join(sorted(CATEGORIES))}")

    rng = param.get("range")
    value = param.get("value")
    if isinstance(rng, list):
        if len(rng) != 2 or not all(is_number(x) for x in rng) or rng[0] > rng[1]:
            errors.append(f"range {rng} is not [min, max]")
        elif is_number(value) and not rng[0] <= value <= rng[1]:
            errors.append(f"value {value} is outside of range {rng}")
    elif rng is not None and not isinstance(rng, str):  # A string for e.g. TODO.
        errors.append(f"range {rng!r} is not [min, max], null or a string")
    return errors


def check_config(params, config):
    """Returns a list of differences between the model entries of a parsed
    config and the documented parameters."""
    errors = []
    for section in ("resources", "systems"):
        documented = [documented_entry(e) for e in params.get(section) or []]
        configured = [e for e in config.get(section) or [] if is_model_entry(e)]

        doc_types = [e["type"] for e in documented]
        cfg_types = [e["type"] for e in configured]
        if doc_types != cfg_types:
            diff = difflib.unified_diff(doc_types, cfg_types, "documented", "config", lineterm="", n=1)
            errors.append(f"{section}: types differ from documented ones:")
            errors += ["  " + line for line in diff]
            continue

        for i, (doc, cfg) in enumerate(zip(documented, configured)):
            where = f"{section}[{i}] ({doc['type']})"
            for name, value in doc.items():
                if name == "type":
                    continue
                if name not in cfg:
                    errors.append(f"{where}: missing parameter {name!r}")
                elif not same_value(value, cfg[name]):
                    errors.append(f"{where}: {name} is {cfg[name]!r}, documented as {value!r}")
            errors += [f"{where}: undocumented parameter {n!r}" for n in cfg if n not in doc]
    return errors


def documented_entry(entry):
    """Returns a documented resource or system as a config entry (type and parameter values)."""
    result = {"type": entry.get("type")}
    result.update((p.get("name"), p.get("value")) for p in entry.get("parameters") or [])
    return result


def is_model_entry(entry):
    typ = entry.get("type", "")
    return typ not in IGNORED_TYPES and "." not in typ


def same_value(a, b):
    """Compares parameter values, treating ints and floats as equal if their
    values are (e.g. 5 and 5.0, as the models accept both), but not bools."""
    if isinstance(a, bool) or isinstance(b, bool):
        return type(a) is type(b) and a == b
    return a == b


def is_number(x):
    return isinstance(x, (int, float)) and not isinstance(x, bool)


if __name__ == "__main__":
    main()
