#!/usr/bin/env python3
"""Converts the documented model parameters into a model config file.

Takes the resources and systems, with their parameter values, from
model-spec/parameters.yaml, and merges them with configs/base.yaml, which
holds everything that is not a model parameter: the seed, and systems
appended after the model's own (reporters). Documentation-only keys
(`label`, `description`, and all parameter fields but `name` and `value`)
are dropped.

Usage: python scripts/params_to_config.py [-p parameters.yaml] [-b base.yaml] [-o config.yaml]
       (defaults: ../model-spec/parameters.yaml, configs/base.yaml, out/default.yaml)

Requires PyYAML.
"""

import argparse
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent

HEADER = """\
# Auto-generated by scripts/params_to_config.py from model-spec/parameters.yaml
# and configs/base.yaml. Do not edit.

"""


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("-p", "--params", default=ROOT.parent / "model-spec" / "parameters.yaml",
                        help="documented parameters (default: %(default)s)")
    parser.add_argument("-b", "--base", default=ROOT / "configs" / "base.yaml",
                        help="non-parameter config parts (default: %(default)s)")
    parser.add_argument("-o", "--output", default=ROOT / "out" / "default.yaml",
                        help="output config file (default: %(default)s)")
    args = parser.parse_args()

    params = load(args.params)
    base = load(args.base)
    config = make_config(params, base)

    output = Path(args.output)
    output.parent.mkdir(parents=True, exist_ok=True)
    with open(output, "w", encoding="utf-8", newline="\n") as f:
        f.write(HEADER)
        yaml.safe_dump(config, f, sort_keys=False, allow_unicode=True)
    print(f"Wrote {output}")


def load(path):
    with open(path, encoding="utf-8") as f:
        return yaml.safe_load(f) or {}


def make_config(params, base):
    """Returns the config for parsed parameters and base documents."""
    unknown = set(base) - {"seed", "tps", "fps", "systems"}
    if unknown:
        raise ValueError(f"unsupported key(s) in base config: {', '.join(sorted(unknown))}")

    config = {k: base[k] for k in ("seed", "tps", "fps") if k in base}
    config["resources"] = [to_entry(e) for e in params.get("resources") or []]
    config["systems"] = [to_entry(e) for e in params.get("systems") or []] + (base.get("systems") or [])
    return config


def to_entry(entry):
    """Converts a documented resource or system into a config entry."""
    result = {"type": entry["type"]}
    for param in entry.get("parameters") or []:
        name = param["name"]
        if name in result:
            raise ValueError(f"duplicate parameter {name!r} in {entry['type']}")
        result[name] = param["value"]
    return result


if __name__ == "__main__":
    main()
